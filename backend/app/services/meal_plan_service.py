"""Meal plan confirmation: idempotent, single-transaction inventory deduction."""

from __future__ import annotations

import hashlib
import json
from datetime import UTC, datetime
from decimal import Decimal
from uuid import UUID

from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from app.core.errors import (
    InsufficientStockError,
    ResourceNotFoundError,
    StateConflictError,
    ValidationError,
)
from app.models.inventory import InventoryItem, InventoryTransaction
from app.models.meal_plan import MealPlan, MealPlanIngredient
from app.models.meal_plan_confirmation import MealPlanConfirmation
from app.repositories.inventory_repository import InventoryRepository
from app.repositories.meal_plan_repository import MealPlanRepository
from app.repositories.recipe_repository import RecipeRepository
from app.schemas.meal_plan import (
    ConfirmItemPayload,
    DeductedItem,
    MealPlanConfirmPayload,
    MealPlanConfirmResponse,
    MealPlanDetailResponse,
    MealPlanIngredientDetailResponse,
    MealPlanItemDetailResponse,
    MissingItem,
    RecipeResponse,
)

QUANTUM = Decimal("0.001")
# Providers that mean "not generated by a model", used to derive source_type.
NON_AI_PROVIDERS = {"manual", "import"}


def _canonical_quantity(value: Decimal) -> str:
    return format(value.quantize(QUANTUM), "f")


def compute_request_hash(plan_id: UUID, items: list[ConfirmItemPayload]) -> str:
    """Stable SHA256 over the normalized request, independent of field order."""
    normalized = {
        "meal_plan_id": str(plan_id),
        "items": [
            {
                "meal_plan_ingredient_id": str(item.meal_plan_ingredient_id),
                "inventory_item_id": str(item.inventory_item_id),
                "actual_quantity": _canonical_quantity(item.actual_quantity),
                "unit": item.unit,
            }
            for item in sorted(items, key=lambda entry: str(entry.meal_plan_ingredient_id))
        ],
    }
    payload = json.dumps(normalized, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def plan_source_type(plan: MealPlan) -> str:
    """Derive the trusted source from the plan, never from the client."""
    provider = (plan.ai_provider or "").strip().lower()
    if not provider:
        raise ValidationError("Meal plan ai_provider must not be blank")
    if provider in NON_AI_PROVIDERS:
        return provider
    return "ai"


class MealPlanService:
    def __init__(
        self,
        plans: MealPlanRepository | None = None,
        inventory: InventoryRepository | None = None,
        recipes: RecipeRepository | None = None,
    ) -> None:
        self._plans = plans or MealPlanRepository()
        self._inventory = inventory or InventoryRepository()
        self._recipes = recipes or RecipeRepository()

    def get_detail(self, db: Session, user_id: UUID, plan_id: UUID) -> MealPlanDetailResponse:
        """Read one plan, keeping both plan and linked recipe access user-scoped."""
        plan = self._plans.get_detail(db, user_id, plan_id)
        if plan is None:
            raise ResourceNotFoundError("Meal plan was not found")

        items: list[MealPlanItemDetailResponse] = []
        for item in sorted(plan.items, key=lambda entry: (entry.sort_order, str(entry.id))):
            recipe = (
                self._recipes.get_visible(db, user_id, item.recipe_id)
                if item.recipe_id is not None
                else None
            )
            ingredients = [
                MealPlanIngredientDetailResponse(
                    id=ingredient.id,
                    inventory_item_id=ingredient.inventory_item_id,
                    display_name=ingredient.display_name,
                    required_quantity=ingredient.required_quantity,
                    actual_quantity=ingredient.actual_quantity,
                    unit=ingredient.unit,
                    is_missing=ingredient.is_missing,
                )
                for ingredient in sorted(item.ingredients, key=lambda entry: str(entry.id))
            ]
            items.append(
                MealPlanItemDetailResponse(
                    id=item.id,
                    recipe_id=item.recipe_id,
                    recipe_snapshot=item.recipe_snapshot,
                    sort_order=item.sort_order,
                    recipe=RecipeResponse.model_validate(recipe) if recipe is not None else None,
                    ingredients=ingredients,
                )
            )

        return MealPlanDetailResponse(
            id=plan.id,
            plan_date=plan.plan_date,
            title=plan.title,
            request_constraints=plan.request_constraints,
            status=plan.status,
            ai_provider=plan.ai_provider,
            confirmed_at=plan.confirmed_at,
            created_at=plan.created_at,
            updated_at=plan.updated_at,
            items=items,
        )

    def confirm(
        self,
        db: Session,
        user_id: UUID,
        plan_id: UUID,
        idempotency_key: str,
        payload: MealPlanConfirmPayload,
    ) -> MealPlanConfirmResponse:
        request_hash = compute_request_hash(plan_id, payload.items)

        # 1. Lock the plan first; this serializes concurrent confirmations of one plan.
        plan = self._plans.get_for_update(db, user_id, plan_id)
        if plan is None:
            raise ResourceNotFoundError("Meal plan was not found")

        # 2. Idempotency must be checked before the status, otherwise a retry after a
        #    successful confirmation would incorrectly return STATE_CONFLICT.
        existing = self._plans.get_confirmation(db, user_id, idempotency_key)
        if existing is not None:
            return self._replay(existing, request_hash)

        if plan.status != "draft":
            raise StateConflictError("Meal plan was already confirmed")

        # Validate the persisted provider before creating confirmation records,
        # locking inventory, or writing any inventory transaction.
        source_type = plan_source_type(plan)

        requested = {item.meal_plan_ingredient_id: item for item in payload.items}
        ingredients = self._plans.list_ingredients(db, plan.id, list(requested))
        if len(ingredients) != len(requested):
            raise ValidationError("Some meal plan ingredients do not belong to this plan")
        by_id = {ingredient.id: ingredient for ingredient in ingredients}

        for item in payload.items:
            ingredient = by_id[item.meal_plan_ingredient_id]
            if ingredient.inventory_item_id != item.inventory_item_id:
                raise ValidationError("inventory_item_id does not match the meal plan ingredient")
            if ingredient.unit != item.unit:
                raise ValidationError("unit does not match the meal plan ingredient")

        # 3. Aggregate per inventory batch; one batch may serve several dishes.
        totals: dict[UUID, Decimal] = {}
        for item in payload.items:
            totals[item.inventory_item_id] = (
                totals.get(item.inventory_item_id, Decimal("0")) + item.actual_quantity
            )

        # 4. Lock each batch exactly once, in a deterministic order.
        ordered_ids = sorted(totals, key=str)
        rows = self._inventory.lock_items_for_update(db, user_id, ordered_ids)
        if len(rows) != len(ordered_ids):
            raise ResourceNotFoundError("Inventory item was not found")
        row_by_id = {row.id: row for row in rows}

        for item in payload.items:
            row = row_by_id[item.inventory_item_id]
            if row.unit != item.unit:
                raise ValidationError("unit does not match the inventory item")

        for inventory_id, total in totals.items():
            row = row_by_id[inventory_id]
            if row.archived_at is not None:
                raise StateConflictError("Inventory item is archived")
            if row.quantity < total:
                raise InsufficientStockError("Insufficient stock for inventory item")

        confirmed_at = datetime.now(UTC)
        deducted = [
            DeductedItem(
                inventory_item_id=inventory_id,
                delta_quantity=-totals[inventory_id],
                unit=row_by_id[inventory_id].unit,
            )
            for inventory_id in ordered_ids
        ]

        all_ingredients = self._plans.list_ingredients(db, plan.id)
        missing = self._collect_missing(all_ingredients, requested)

        snapshot = MealPlanConfirmResponse(
            meal_plan_id=plan.id,
            status="confirmed",
            confirmed_at=confirmed_at,
            deducted=deducted,
            missing=missing,
        )

        # 5. The confirmation row must exist before transactions reference operation_id.
        confirmation = MealPlanConfirmation(
            user_id=user_id,
            meal_plan_id=plan.id,
            idempotency_key=idempotency_key,
            request_hash=request_hash,
            result_snapshot=snapshot.model_dump(mode="json"),
        )
        self._plans.add_confirmation(db, confirmation)
        try:
            db.flush()
        except IntegrityError:
            # A concurrent request won the (user_id, idempotency_key) race.
            db.rollback()
            existing = self._plans.get_confirmation(db, user_id, idempotency_key)
            if existing is not None:
                return self._replay(existing, request_hash)
            raise StateConflictError("Confirmation conflicted with another request") from None

        for ingredient in all_ingredients:
            requested_item = requested.get(ingredient.id)
            if requested_item is None:
                ingredient.actual_quantity = None
                ingredient.is_missing = True
            else:
                ingredient.actual_quantity = requested_item.actual_quantity
                ingredient.is_missing = (
                    requested_item.actual_quantity < ingredient.required_quantity
                )

        for inventory_id in ordered_ids:
            row = row_by_id[inventory_id]
            self._deduct(row, totals[inventory_id])
            self._inventory.add_transaction(
                db,
                InventoryTransaction(
                    user_id=user_id,
                    inventory_item_id=inventory_id,
                    delta_quantity=-totals[inventory_id],
                    unit=row.unit,
                    reason="meal_plan_deduction",
                    source_type=source_type,
                    operation_id=confirmation.id,
                ),
            )

        self._plans.mark_confirmed(db, plan, confirmed_at)
        db.commit()
        return snapshot

    @staticmethod
    def _deduct(row: InventoryItem, total: Decimal) -> None:
        row.quantity = row.quantity - total
        row.version = row.version + 1

    @staticmethod
    def _collect_missing(
        ingredients: list[MealPlanIngredient],
        requested: dict[UUID, ConfirmItemPayload],
    ) -> list[MissingItem]:
        missing: list[MissingItem] = []
        for ingredient in ingredients:
            item = requested.get(ingredient.id)
            if item is None:
                missing.append(
                    MissingItem(
                        meal_plan_ingredient_id=ingredient.id,
                        display_name=ingredient.display_name,
                        required_quantity=ingredient.required_quantity,
                        actual_quantity=None,
                        unit=ingredient.unit,
                    )
                )
            elif item.actual_quantity < ingredient.required_quantity:
                missing.append(
                    MissingItem(
                        meal_plan_ingredient_id=ingredient.id,
                        display_name=ingredient.display_name,
                        required_quantity=ingredient.required_quantity,
                        actual_quantity=item.actual_quantity,
                        unit=ingredient.unit,
                    )
                )
        return missing

    @staticmethod
    def _replay(existing: MealPlanConfirmation, request_hash: str) -> MealPlanConfirmResponse:
        if existing.request_hash != request_hash:
            raise StateConflictError("Idempotency key was reused with different content")
        return MealPlanConfirmResponse.model_validate(existing.result_snapshot)
